// Writes docs/PHOTO_CREDITS.md from the sidecar .json files in photos/originals/ (run after npm run photos).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SRC = path.join(ROOT, 'photos/originals');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const rows = walk(SRC)
  .filter((f) => f.endsWith('.json'))
  .map((f) => ({ key: path.relative(SRC, f).split(path.sep).join('/').replace(/\.json$/, ''), ...JSON.parse(fs.readFileSync(f, 'utf8')) }))
  .sort((a, b) => a.key.localeCompare(b.key, 'en', { numeric: true }));

const cell = (s) => String(s || '').replace(/\|/g, '\\|');
const link = (u) => (/^https?:\/\//.test(u || '') ? `[${u.replace(/^https?:\/\//, '').slice(0, 60)}](${u})` : cell(u));
const table = (list) => [
  '| Slot key | Image | Credit | Source |',
  '|---|---|---|---|',
  ...list.map((r) => `| \`${r.key}\` | ${cell(r.alt)}${r.caption ? ` (${cell(r.caption)})` : ''} | ${cell((r.credit || '').replace(/^Photo:\s*/, ''))} | ${link(r.source)} |`),
].join('\n');

const gallery = rows.filter((r) => /^StartNet Gallery\//.test(r.source || ''));
const permission = rows.filter((r) => !r.stock && !gallery.includes(r) && /^event\//.test(r.key));
const own = rows.filter((r) => !r.stock && !gallery.includes(r) && !permission.includes(r));
const stock = rows.filter((r) => r.stock);

const md = `# Photo credits

Every photograph on startnet.in, where it came from and who owns it. Generated by \`node tools/images/credits.mjs\` from the
.json files in photos/originals/ (${rows.length} photos). Every photo is shown in grayscale (tools/images/photos.mjs).

## StartNet Gallery (StartNet's own event photos)

Supplied by StartNet in the "StartNet Gallery" folder (October 2026) and imported by \`tools/images/gallery-import.mjs\`
(\`photos/stock/gallery-map.json\`). Captions name the event each photo was taken at; an upcoming event that has no photos
yet shows photos of its closest past StartNet event, with that event's caption. Group shots: StartNet confirms consent
under its photo policy.

${table(gallery)}

## StartNet event photos used with the owners' permission

${table(permission)}

## StartNet's own photos from LinkedIn, YouTube and the archived startnet.in

${table(own)}

## Licensed library (Unsplash License)

Free for commercial use, no attribution required; credited anyway. Indian subjects, from photographers in India,
chosen per page section (\`photos/stock/picks.json\`, downloaded by \`tools/images/stock-picks.mjs\`). A stock photo never
stands for a real StartNet person or event.

${table(stock)}
`;
fs.writeFileSync(path.join(ROOT, 'docs/PHOTO_CREDITS.md'), md);
console.log(`[credits] ${rows.length} photos: gallery ${gallery.length}, permission ${permission.length}, own ${own.length}, stock ${stock.length}`);

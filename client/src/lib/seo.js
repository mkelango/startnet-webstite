// Shared SEO / AEO / GEO helpers (Book 1 Part B §7.4, §9; Book 3 §5.7).
// Every JSON-LD builder here only emits facts that exist in the data: a missing field is left out,
// never filled with a guess, and placeholder text ("[placeholder — …]") is never published as a fact.

/** Public origin for canonical, hreflang and JSON-LD URLs (override with VITE_SITE_ORIGIN at build time). */
export const SITE_ORIGIN = String(import.meta.env.VITE_SITE_ORIGIN || 'https://startnet.in').replace(/\/+$/, '');

/** @id of the site-wide Organization and WebSite nodes declared in index.html. */
export const ORG_ID = `${SITE_ORIGIN}/#organization`;
export const WEBSITE_ID = `${SITE_ORIGIN}/#website`;
export const ORG_REF = { '@id': ORG_ID };

/** Absolute URL for a site path ("/vibe" → "https://startnet.in/vibe"). Absolute URLs pass through. */
export const absUrl = (p) => {
  if (typeof p !== 'string' || !p) return SITE_ORIGIN + '/';
  if (/^https?:\/\//i.test(p)) return p;
  return `${SITE_ORIGIN}${p.startsWith('/') ? p : `/${p}`}`;
};

/** The localised path of a base path ("/vibe", 'ta' → "/ta/vibe"). */
export const langPath = (p, lang) => (lang === 'ta' ? (p === '/' ? '/ta' : `/ta${p}`) : p);

/** Brand of a base path, for the share image: research | vibe | connect | women | x | null. */
export function brandOfPath(basePath = '/') {
  const m = /^\/(research|vibe|connect|women|startnet-x)(\/|$)/.exec(basePath);
  if (!m) return null;
  return m[1] === 'startnet-x' ? 'x' : m[1];
}

/** 1200×630 share image per brand (generated by tools/seo/og-images.mjs into client/public/og/). */
export const ogImageFor = (brand) => absUrl(`/og/${brand || 'startnet'}.png`);
export const OG_IMAGE_SIZE = { width: 1200, height: 630 };

/** True for text that is a placeholder or unconfirmed value, which must never be published as a fact. */
export const isPlaceholder = (v) =>
  typeof v !== 'string' ||
  !v.trim() ||
  /\[[^\]]*(placeholder|to be (supplied|confirmed)|confirm|tbc|draft|இடநிரப்பி|உறுதி)[^\]]*\]|^to be confirmed$|^tbc$/i.test(v.trim());

/**
 * Stricter: true when text carries ANY bracketed mark — "[placeholder — …]", "[confirm]", "[C]" confidence tags,
 * spaced Tamil marks ("[உறுதி செய்யப்பட உள்ளது]") — or is a placeholder. Used for anything handed to answer engines
 * as a fact (FAQ answers): an indicative or unconfirmed value stays on the page with its chip, but is never quoted.
 */
export const hasMarks = (s) => isPlaceholder(s) || /\[[^\]]*\]/.test(s);

/** A string with placeholder brackets removed, or undefined when nothing real is left. */
export const factOrUndefined = (v) => (isPlaceholder(v) ? undefined : v.trim());

/** Query keys that do not change the content (tracking). Any other key makes the URL a filter state. */
const TRACKING = /^(utm_[a-z]+|gclid|fbclid|msclkid|ref|src|mc_cid|mc_eid)$/i;
export function isFilterState(search) {
  if (!search || search === '?') return false;
  const params = new URLSearchParams(search);
  for (const k of params.keys()) if (!TRACKING.test(k)) return true;
  return false;
}

/** Drop undefined / null / '' / empty arrays recursively, so JSON-LD never carries empty properties. */
export function compact(value) {
  if (Array.isArray(value)) {
    const out = value.map(compact).filter((v) => v !== undefined);
    return out.length ? out : undefined;
  }
  if (value && typeof value === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(value)) {
      const c = compact(v);
      if (c !== undefined) out[k] = c;
    }
    return Object.keys(out).length ? out : undefined;
  }
  if (value === null || value === '' || (typeof value === 'number' && Number.isNaN(value))) return undefined;
  return value;
}

const LANG_CODES = { en: 'en-IN', ta: 'ta-IN', bilingual: ['en-IN', 'ta-IN'], english: 'en-IN', tamil: 'ta-IN' };
export const inLanguageOf = (v) => {
  if (Array.isArray(v)) return v.flatMap((x) => [].concat(inLanguageOf(x) || [])).filter(Boolean);
  return typeof v === 'string' ? LANG_CODES[v.toLowerCase()] : undefined;
};

/** The page's own localised path: base paths get /ta on Tamil pages; already-localised paths pass through. */
const ownPath = (path, lang) => (lang === 'ta' && !/^\/ta(\/|$)/.test(path || '') ? langPath(path || '/', 'ta') : path);

/** WebPage node for a page (ties the page to the site and organization). `path` may be the base or localised path. */
export function webPageLd({ path, name, description, lang = 'en', type = 'WebPage', about }) {
  const own = ownPath(path, lang);
  return compact({
    '@context': 'https://schema.org',
    '@type': type,
    '@id': `${absUrl(own)}#webpage`,
    url: absUrl(own),
    name,
    description,
    inLanguage: lang === 'ta' ? 'ta-IN' : 'en-IN',
    isPartOf: { '@id': WEBSITE_ID },
    publisher: ORG_REF,
    about,
  });
}

/**
 * Course (Book 1 §9.4: Vibe Academy, Rise Academy, Founder Switch, Fellowship, Launchpad).
 * `price` is only published when it is a real number or "free".
 */
export function courseLd({ name, description, path, lang = 'en', inLanguage, price, educationalLevel, timeRequired, courseMode }) {
  const free = typeof price === 'string' && /^free$/i.test(price.trim());
  const amount = typeof price === 'number' && price >= 0 ? price : undefined;
  return compact({
    '@context': 'https://schema.org',
    '@type': 'Course',
    '@id': `${absUrl(path)}#course`,
    name,
    description,
    url: absUrl(langPath(path, lang)),
    // Google's Course markup wants the provider's type and name inline, not only a reference.
    provider: { '@type': 'Organization', '@id': ORG_ID, name: 'StartNet', url: `${SITE_ORIGIN}/` },
    // Teaching language only when the programme states it: the page language is not the course language.
    inLanguage: inLanguageOf(inLanguage),
    educationalLevel,
    timeRequired,
    isAccessibleForFree: free ? true : undefined,
    offers:
      free || amount !== undefined
        ? { '@type': 'Offer', price: free ? 0 : amount, priceCurrency: 'INR', category: free ? 'Free' : 'Paid' }
        : undefined,
    hasCourseInstance: courseMode ? { '@type': 'CourseInstance', courseMode } : undefined,
  });
}

const ATTENDANCE = {
  'in-person': 'https://schema.org/OfflineEventAttendanceMode',
  online: 'https://schema.org/OnlineEventAttendanceMode',
  hybrid: 'https://schema.org/MixedEventAttendanceMode',
};

/**
 * Event (Book 1 §9.4). Returns null unless the date is confirmed: an unconfirmed date published as a
 * startDate would be a false fact in search results. Venue / city are included only when real.
 */
export function eventLd(e, { path, lang = 'en' } = {}) {
  if (!e || !e.dateConfirmed || !e.date) return null;
  const venue = factOrUndefined(e.venue);
  const city = factOrUndefined(e.city);
  const online = e.format === 'online';
  const location = online
    ? { '@type': 'VirtualLocation', url: absUrl(langPath(path, lang)) }
    : venue || city
      ? { '@type': 'Place', name: venue || city, address: { '@type': 'PostalAddress', addressLocality: city, addressRegion: 'Tamil Nadu', addressCountry: 'IN' } }
      : undefined;
  if (!location) return null;
  const free = e.price === 'free';
  return compact({
    '@context': 'https://schema.org',
    '@type': 'Event',
    '@id': `${absUrl(path)}#event`,
    name: lang === 'ta' && e.titleTa ? e.titleTa : e.title,
    description: lang === 'ta' && e.summaryTa ? e.summaryTa : e.summary,
    startDate: e.date,
    endDate: e.endDate,
    eventStatus: e.status === 'cancelled' ? 'https://schema.org/EventCancelled' : 'https://schema.org/EventScheduled',
    eventAttendanceMode: ATTENDANCE[e.format],
    location,
    organizer: ORG_REF,
    inLanguage: inLanguageOf(e.language),
    url: absUrl(langPath(path, lang)),
    image: ogImageFor(e.brand),
    offers: free
      ? { '@type': 'Offer', price: 0, priceCurrency: 'INR', availability: 'https://schema.org/InStock', url: absUrl(langPath(path, lang)) }
      : undefined,
    isAccessibleForFree: free ? true : undefined,
  });
}

/** Article / Report (T09). Returns null for placeholder stories. */
export function articleLd({ headline, description, path, lang = 'en', datePublished, dateModified, type = 'Article', placeholder, image }) {
  if (placeholder || !headline) return null;
  return compact({
    '@context': 'https://schema.org',
    '@type': type,
    '@id': `${absUrl(path)}#article`,
    headline: String(headline).slice(0, 110),
    description,
    url: absUrl(langPath(path, lang)),
    mainEntityOfPage: absUrl(langPath(path, lang)),
    inLanguage: lang === 'ta' ? 'ta-IN' : 'en-IN',
    datePublished,
    dateModified: dateModified || datePublished,
    author: ORG_REF,
    publisher: ORG_REF,
    image: image || ogImageFor(null),
  });
}

/** ItemList for listing pages: items = [{ name, path }]. */
export function itemListLd({ name, items, lang = 'en' }) {
  const list = (items || []).filter((i) => i && i.name && i.path);
  if (!list.length) return null;
  return compact({
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    name,
    numberOfItems: list.length,
    itemListElement: list.map((it, i) => ({ '@type': 'ListItem', position: i + 1, name: it.name, url: absUrl(langPath(it.path, lang)) })),
  });
}

/**
 * FAQPage from [{ question, answer, answerText? }]: plain strings only (`answerText` is the plain version of a rich
 * `answer` element), and never a Q&A that still carries a placeholder or mark.
 */
export function faqLd(items) {
  const list = (items || [])
    .map((it) => (it && typeof it.answerText === 'string' ? { ...it, answer: it.answerText } : it))
    .filter((it) => it && typeof it.question === 'string' && typeof it.answer === 'string' && !hasMarks(it.question) && !hasMarks(it.answer));
  if (!list.length) return null;
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: list.map((it) => ({ '@type': 'Question', name: it.question, acceptedAnswer: { '@type': 'Answer', text: it.answer } })),
  };
}

const pick = (ta, en) => (ta === undefined || ta === null || ta === '' ? en : ta);

function localiseBlock(en, ta) {
  if (ta === undefined || ta === null) return en;
  if (typeof en === 'string') return typeof ta === 'string' ? ta : en;
  if (en.list) return { list: en.list.map((li, i) => pick(ta.list?.[i], li)) };
  if (en.table) {
    const tt = ta.table || {};
    return {
      table: {
        head: en.table.head.map((h, i) => pick(tt.head?.[i], h)),
        rows: en.table.rows.map((row, r) => row.map((cell, c) => pick(tt.rows?.[r]?.[c], cell))),
      },
    };
  }
  if (en.links) return { links: en.links.map((l, i) => ({ ...l, label: pick(ta.links?.[i], l.label) })) };
  return en;
}

/**
 * The Tamil view of one English legal page: every string is swapped for its Tamil draft where one exists,
 * and falls back to English otherwise. Section ids and link targets are kept from English.
 */
export function localiseLegal(slug, page) {
  const ta = Object.prototype.hasOwnProperty.call(LEGAL_TA, slug) ? LEGAL_TA[slug] : null;
  if (!ta) return page;
  return {
    ...page,
    title: pick(ta.title, page.title),
    description: pick(ta.description, page.description),
    intro: pick(ta.intro, page.intro),
    sections: page.sections.map((s) => {
      const ts = ta.sections?.[s.id];
      if (!ts) return s;
      return { ...s, title: pick(ts.title, s.title), blocks: s.blocks.map((b, i) => localiseBlock(b, ts.blocks?.[i])) };
    }),
  };
}

/** Title of a legal page in the given language. */
export const legalTitle = (slug, page, lang) =>
  lang === 'ta' && Object.prototype.hasOwnProperty.call(LEGAL_TA, slug) ? LEGAL_TA[slug].title || page.title : page.title;
